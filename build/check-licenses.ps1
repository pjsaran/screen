<#
.SYNOPSIS
    Mechanically verifies every NuGet dependency (including transitive ones) carries a
    licence acceptable for commercial use, and keeps a committed report so drift is
    visible in review.

.DESCRIPTION
    SPEC §2: "The build must generate a dependency licence report and fail if any
    dependency falls outside the acceptable list, including transitive ones. Commit
    the generated report so drift is visible in review. A licence that was fine at
    version 3 is not guaranteed fine at version 4."

    Acceptable licences (SPEC §2): MIT, Apache-2.0, BSD-2/3-Clause, MS-PL, ISC,
    Unlicense, public domain (CC0). Everything else — GPL, AGPL, LGPL-static, MS-RL,
    "free for non-commercial", revenue-capped community editions — fails the build.
    Real example this gate exists for: FluentAssertions >= 8 moved to a paid licence.

    Behaviour:
      1. Runs nuget-license over the solution with transitive analysis.
      2. Fails on any package whose licence is not in the allowed list.
      3. Regenerates build/licenses/THIRD-PARTY.md and, unless -Update is passed,
         fails if it differs from the committed copy (drift must be reviewed).

.PARAMETER Update
    Rewrite the committed report instead of failing on difference. Use after an
    intentional dependency change, and commit the result.
#>
[CmdletBinding()]
param(
    [switch]$Update,
    [string]$RepoRoot = (Split-Path $PSScriptRoot -Parent)
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$solution   = Join-Path $RepoRoot 'Captr.slnx'
$reportPath = Join-Path $PSScriptRoot 'licenses\THIRD-PARTY.md'
New-Item -ItemType Directory -Force (Split-Path $reportPath) | Out-Null

# The allowed list is exactly SPEC §2's list. 'BSD-2-Clause'/'BSD-3-Clause' are the
# SPDX ids for the BSD variants; CC0-1.0 is the SPDX id for public-domain dedication.
$allowed = 'MIT;Apache-2.0;BSD-2-Clause;BSD-3-Clause;MS-PL;ISC;Unlicense;CC0-1.0'

# Documented exemptions — build-time-only inputs to the CsWin32 source generator
# (PrivateAssets=all). They never ship: only the C# code generated from them is
# compiled into Captr, so SPEC §2 (which governs what we redistribute) is not
# engaged. Do NOT add a shipping package here; widen nothing without a licensing
# decision recorded in this comment.
$buildTimeOnly = 'Microsoft.Windows.SDK.Win32Metadata;Microsoft.Windows.SDK.Win32Docs;Microsoft.Windows.WDK.Win32Metadata'

Push-Location $RepoRoot
try {
    # --- 1+2. Validate: any package outside the allowed list fails the run ---------
    $jsonOut = & dotnet nuget-license -i $solution -t -a $allowed -ignore $buildTimeOnly -include-ignored -o JsonPretty 2>&1
    $exit = $LASTEXITCODE
    $parsed = $jsonOut | Where-Object { $_ -is [string] } | Out-String | ConvertFrom-Json
    if ($exit -ne 0) {
        $bad = @($parsed | Where-Object { $_.PSObject.Properties['ValidationErrors'] -and $_.ValidationErrors })
        Write-Host "DISALLOWED LICENCES FOUND:" -ForegroundColor Red
        foreach ($p in $bad) {
            Write-Host ("  {0} {1}  licence: {2}" -f $p.PackageId, $p.PackageVersion, $p.License)
        }
        throw "Licence gate failed (SPEC §2). Remove or replace the packages above; do not widen the allowed list without a licensing decision."
    }

    # --- 3. Regenerate the committed report ---------------------------------------
    $lines = @(
        '# Third-party dependency licences'
        ''
        '> Generated by build/check-licenses.ps1 — do not edit by hand.'
        '> Regenerate with:  pwsh build/check-licenses.ps1 -Update'
        '> Every licence below must be in the SPEC §2 allowed list; the build fails otherwise.'
        ''
        '| Package | Version | Licence |'
        '|---|---|---|'
    )
    $rows = $parsed | Sort-Object PackageId, PackageVersion | ForEach-Object {
        # Exempted build-time-only packages carry no resolved License property;
        # label them so the report stays honest about why they pass.
        $licence = if ($_.PSObject.Properties['License']) { $_.License }
                   else { 'build-time only, not redistributed (see exemption note in check-licenses.ps1)' }
        '| {0} | {1} | {2} |' -f $_.PackageId, $_.PackageVersion, $licence
    }
    $lines += $rows
    # The bundled FFmpeg binary is not a NuGet package; record it here so the report
    # is the single complete licence inventory.
    $ffLock = Get-Content (Join-Path $PSScriptRoot 'ffmpeg.lock.json') -Raw | ConvertFrom-Json
    $lines += ''
    $lines += '## Bundled binaries (non-NuGet)'
    $lines += ''
    $lines += '| Component | Build | Licence |'
    $lines += '|---|---|---|'
    # The licence follows the pinned flavor. GPL is a recorded decision for
    # internal-only deployment (docs/developer-guide/design-decisions.md); the
    # obligations and the exit path are in docs/ffmpeg-source-offer.md.
    $ffLicence = if ($ffLock.PSObject.Properties['licenceFlavor'] -and $ffLock.licenceFlavor -eq 'gpl') {
        'GPL-3.0 (internal deployment only — see docs/ffmpeg-source-offer.md)'
    } else {
        'LGPL-2.1-or-later'
    }
    $lines += "| FFmpeg (child process, unmodified) | $($ffLock.buildId) | $ffLicence |"
    $lines += ''
    $lines += 'FFmpeg licence texts ship alongside the binary; the written source offer is in docs/ffmpeg-source-offer.md.'

    $newReport = ($lines -join "`r`n") + "`r`n"
    $oldReport = if (Test-Path $reportPath) { Get-Content $reportPath -Raw } else { '' }

    if ($Update) {
        Set-Content $reportPath $newReport -Encoding utf8 -NoNewline
        Write-Host "Report updated: $reportPath (commit this change)"
    }
    elseif ($newReport -ne $oldReport) {
        throw ("The dependency licence report is out of date — the dependency set changed. " +
               "Run 'pwsh build/check-licenses.ps1 -Update', review the diff, and commit it (SPEC §2: drift must be visible in review).")
    }
    else {
        Write-Host "Licence gate passed; committed report is current ($(@($rows).Count) packages)."
    }
}
finally {
    Pop-Location
}
