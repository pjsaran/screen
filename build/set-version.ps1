<#
.SYNOPSIS
    Sets Captr's version. This is the ONLY place a version number is ever typed.

.DESCRIPTION
    SPEC §11 requires the version to be defined in exactly one place. That place is
    Version.props; every other version in the product is derived from it:

      * assembly, file, and informational versions  — Directory.Build.props
      * the installer's AppVersion and file name    — build/installer/version.iss,
                                                      regenerated by make-installer.ps1
      * the Diagnostics page's build identity       — AssemblyInformationalVersion

    So bumping a version is one edit, and this script makes that edit safely: it
    checks the new value is a valid version, refuses to go backwards unless told to,
    and shows exactly what changed.

    It deliberately does NOT commit, tag, or push. new-release.ps1 does those, in
    that order, after the build has passed — a version bump that is committed before
    anything is built is a commit that might not compile.

.PARAMETER Version
    The new version, as MAJOR.MINOR.PATCH (e.g. 0.2.0). Optional pre-release and
    build suffixes are accepted (0.2.0-beta.1), because the .NET SDK and Inno Setup
    both handle them.

.PARAMETER Bump
    Instead of naming a version, raise one part of the current one: major, minor, or
    patch. Lower parts reset to zero, which is what semantic versioning means.

.PARAMETER AllowDowngrade
    Permit setting a version lower than the current one. Off by default because it is
    almost always a typo, and a downgrade that reaches a release is one the installer
    itself will refuse to install.

.EXAMPLE
    pwsh build/set-version.ps1 -Bump minor
    0.1.0 -> 0.2.0

.EXAMPLE
    pwsh build/set-version.ps1 -Version 1.0.0
#>
[CmdletBinding(DefaultParameterSetName = 'Explicit')]
param(
    [Parameter(ParameterSetName = 'Explicit', Position = 0)]
    [string] $Version,

    [Parameter(ParameterSetName = 'Bump', Mandatory = $true)]
    [ValidateSet('major', 'minor', 'patch')]
    [string] $Bump,

    [switch] $AllowDowngrade,

    [string] $RepoRoot = (Split-Path $PSScriptRoot -Parent)
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$versionPropsPath = Join-Path $RepoRoot 'Version.props'
if (-not (Test-Path $versionPropsPath)) { throw "Version.props not found at $versionPropsPath." }

[xml] $props = Get-Content $versionPropsPath
$current = $props.Project.PropertyGroup.CaptrVersion.Trim()

# ---- Work out the new version ---------------------------------------------------
if ($PSCmdlet.ParameterSetName -eq 'Bump') {
    if ($current -notmatch '^(\d+)\.(\d+)\.(\d+)') {
        throw "Cannot bump '$current': it is not MAJOR.MINOR.PATCH."
    }

    $major = [int]$Matches[1]; $minor = [int]$Matches[2]; $patch = [int]$Matches[3]
    switch ($Bump) {
        'major' { $major++; $minor = 0; $patch = 0 }
        'minor' { $minor++; $patch = 0 }
        'patch' { $patch++ }
    }
    $Version = "$major.$minor.$patch"
}

if (-not $Version) {
    # No arguments: report rather than guess. Being able to ask "what version is
    # this?" without changing anything is worth more than a default bump.
    Write-Host "Current version: $current"
    return
}

# MSBuild, NuGet, and Inno Setup all accept this shape; anything else fails much
# later, in a message that does not mention the version.
if ($Version -notmatch '^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$') {
    throw "'$Version' is not a valid version. Use MAJOR.MINOR.PATCH, optionally with a -prerelease suffix."
}

if ($Version -eq $current) {
    Write-Host "Version is already $current — nothing to do."
    return
}

# ---- Refuse to go backwards by accident -----------------------------------------
$currentCore = [version]($current -replace '-.*$', '')
$newCore = [version]($Version -replace '-.*$', '')
if ($newCore -lt $currentCore -and -not $AllowDowngrade) {
    throw "$Version is lower than the current $current. Pass -AllowDowngrade if that is really what you want."
}

# ---- Write it -------------------------------------------------------------------
# A targeted text replacement rather than an XML round-trip: saving the XmlDocument
# would reformat the file and throw away the comment that explains why it exists.
$text = Get-Content $versionPropsPath -Raw
$updated = $text -replace '(<CaptrVersion>)[^<]*(</CaptrVersion>)', "`${1}$Version`${2}"
if ($updated -eq $text) { throw "Could not find <CaptrVersion> in $versionPropsPath." }

[System.IO.File]::WriteAllText($versionPropsPath, $updated, (New-Object System.Text.UTF8Encoding $false))

Write-Host "$current -> $Version" -ForegroundColor Green
Write-Host "Updated $versionPropsPath"
Write-Host ""
Write-Host "Next: pwsh build/new-release.ps1   (builds, tests, packages, tags, and publishes this version)"
